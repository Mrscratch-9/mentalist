export const STRINGS: Record<UiLang, Record<StringKey, string>> = { en, es };

export type Params = Record<string, string | number>;

export function t(lang: UiLang, key: StringKey, params?: Params): string {
  const text = STRINGS[lang][key];
  return params ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : text;
}

/** `t` bound to a language. */
export type Translate = (key: StringKey, params?: Params) => string;
export const translator = (lang: UiLang): Translate => (key, params) => t(lang, key, params);
