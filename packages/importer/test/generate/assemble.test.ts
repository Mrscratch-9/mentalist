import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { loadDir, validate } from "@mentalist/pipeline";
import { assemble, collectLinkTargets } from "../../src/generate/assemble.ts";
import { FILE_NAMES, HEADER, renderYaml } from "../../src/generate/write.ts";
import { BASE, ch, ep, page } from "./helpers.ts";

const dir = mkdtempSync(join(tmpdir(), "imp-asm-"));
afterAll(() => rmSync(dir, { recursive: true, force: true }));

const credit = (role: string, characterPage: string) => ({ role, actor: "Act", characterPage });
const episodes = [
  ep(1, 1, "Pilot", 11, { guests: [credit("Pat", "Pat Person")] }),
  ep(1, 2, "Two", 12, { recurring: [credit("Pat", "Pat Person")] }),
  ep(1, 3, "Three", 13),
  ep(7, 13, "Finale", 14),
];
const characters = [
  ch("Pat Person", { actor: "Act", job: "Cop, later chief", categories: ["Recurring characters"] }),
  ch("Late One", { first: "Three" }),
  ch("Lost", { first: "Nowhere" }),
];
const pages = [
  { page: page("Pilot", "==Trivia==\n* Fact [[Late One]].\n* Unknown [[Zzz]]."), kind: "episode" as const },
  { page: page("Pat Person", "==Trivia==\n* Char fact.", 3), kind: "character" as const },
];
const input = { episodes, characters, pages, wikiBase: BASE, tmdb: undefined, tmdbShowId: 5920 };

describe("assemble", () => {
  const a = assemble(input);
  it("produces the four generated documents and a validating canon set", () => {
    expect(Object.keys(a.docs).sort()).toEqual([...FILE_NAMES].sort());
    for (const [name, doc] of Object.entries(a.docs)) writeFileSync(join(dir, name), renderYaml(doc));
    const { docs, errors } = loadDir(dir);
    expect(errors).toEqual([]);
    expect(validate(docs)).toEqual([]);
  });
  it("reports counts only", () => {
    expect(a.report).toMatchObject({
      episodes: 4, missingSynopsis: 4, persons: 2, recurring: 1, skippedUnresolved: 1,
      guestClaims: 2, fans: 3,
    });
    expect(a.report.fansBySeason).toEqual({ 1: 1, 7: 2 });
  });
  it("is deterministic", () => {
    expect(renderYaml(assemble(input).docs["characters.yaml"]!)).toBe(renderYaml(a.docs["characters.yaml"]!));
  });
  it("collects link targets that are not already known page titles", () => {
    expect(collectLinkTargets(input).sort()).toEqual(["Nowhere", "Zzz"]);
  });
});

describe("renderYaml", () => {
  it("starts with the header and sorts keys stably", () => {
    const text = renderYaml({ b: [{ z: 1, a: "x: y" }], a: [] });
    expect(text.startsWith(HEADER)).toBe(true);
    expect(HEADER).toContain("Generated by pnpm data:import — do not edit. Spoilers: do not open outside the app.");
    expect(text.indexOf("\na:")).toBeLessThan(text.indexOf("\nb:"));
    expect(text).toContain('a: "x: y"');
  });
});
